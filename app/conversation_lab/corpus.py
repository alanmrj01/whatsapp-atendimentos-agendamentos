def _semantic_cases(
    family: str,
    phrases: tuple[str, ...],
    intent: ConversationIntent | None,
    act: ConversationAct | None = None,
) -> tuple[SemanticCase, ...]:
    return tuple(
        SemanticCase(family, phrase, intent, act)
        for phrase in phrases
    )


